def extract(source):
    found = {}
    base = Path(source)
    for path in sorted(list((base / "doc/classes").glob("*.xml")) + list((base / "modules").glob("*/doc_classes/*.xml"))):
        root = ET.parse(path).getroot()
        cls = root.get("name")
        if cls == "EditorSettings":
            continue
        for kind in ("member", "constant", "method"):
            for item in root.iter(kind):
                description = item.find("description") if kind == "method" else item
                text = " ".join(((description.text if description is not None else "") or "").split())
                if KEYWORDS.search(text):
                    found[f"{cls}.{item.get('name')}"] = (text, path.relative_to(base).as_posix(), kind)
    return found


def classify(key, kind):
    if kind == "member":
        return CLASSIFY.get(key)
    if kind == "method":
        return METHODS.get(key) or METHOD_CLASSES.get(key.split(".")[0])
    return CONSTANTS.get(key) or CONSTANT_CLASSES.get(key.split(".")[0])


def main():
    rules = {rule["id"] for path in (ROOT / "addons/render_lens/rules").glob("*.json") for rule in json.loads(path.read_text(encoding="utf-8"))}
    entries = {}
    for version, source in zip(VERSIONS, sys.argv[1:5]):
        for key, (text, location, kind) in extract(source).items():
            entry = entries.setdefault(key, {"member": key, "kind": kind, "note": text, "source": {}})
            entry["source"][version] = f"https://github.com/godotengine/godot/blob/{VERSIONS[version]}/{location}"
    missing = sorted(key for key, entry in entries.items() if classify(key, entry["kind"]) is None)
    assert not missing, "Unclassified notes:\n" + "\n".join(missing)
    stale = sorted((set(CLASSIFY) | set(CONSTANTS) | set(METHODS)) - set(entries))
    assert not stale, "Classified keys without a matching note:\n" + "\n".join(stale)
    for key, entry in entries.items():
        status, _, detail = classify(key, entry["kind"]).partition(":")
        entry["status"] = {"rule": "covered", "notcost": "not_a_cost", "exclude": "excluded"}[status]
        if status == "rule":
            entry["rules"] = detail.split(",")
            for rule_id in entry["rules"]:
                assert rule_id in rules, f"{key}: rule {rule_id} is missing"
        else:
            entry["reason"] = detail
        if key in NOTES:
            entry["note_on_coverage"] = NOTES[key]
    items = [entries[key] for key in sorted(entries)]
    summary = {"notes": len(items)}
    for kind in ("member", "constant", "method"):
        summary[kind + "s"] = sum(1 for item in items if item["kind"] == kind)
    for status in ("covered", "excluded", "not_a_cost"):
        summary[status] = sum(1 for item in items if item["status"] == status)
    document = {
        "scope": "Every property, project-setting, enum-constant and method description in the Godot 4.4-stable, 4.5.2-stable, 4.6.3-stable and 4.7.2-stable class reference (doc/classes and module doc_classes, EditorSettings excluded) whose text matches a performance keyword.",
        "versions": VERSIONS,
        "keywords": KEYWORDS.pattern,
        "method": "Keyword matches are candidates. Each is classified by hand: covered by named rules (rule quotes are verified against the same XML at build time), not a cost (the keyword describes motion, precision or a cost-free option), or excluded with a reason. Server and low-level API constants are classified per class (server enums mirror node and setting options classified at member level). Methods are classified per class (math, string and container tips; server setters mirroring members) unless listed individually; method costs that depend on how often a script calls them are covered by the scripts.frame_* text scan.",
        "summary": summary,
        "notes": items,
    }
    (ROOT / "docs/GODOT_PERF_NOTES.json").write_text(json.dumps(document, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(summary)


if __name__ == "__main__":
    main()
