"""Map every runtime WARN_PRINT message in Godot 4.4 to 4.7.2 (servers/, drivers/, scene/, modules/) to a rule or an exclusion.

Usage: python scripts/godot_runtime_warnings.py <4.4-stable source> <4.5.2-stable source> <4.6.3-stable source> <4.7.2-stable source> [--dump]
Writes docs/GODOT_RUNTIME_WARNINGS.json and fails if a message is unmapped or a mapped rule is missing.
Also writes addons/render_lens/server_sync_calls.gd: every RenderingServer/PhysicsServer2D/3D method that waits for the
server thread (FUNC*R/FUNC*RC wrappers, which run MAIN_THREAD_SYNC_CHECK) in any of the four versions.
--dump prints every message with its file instead, for classification.
"""
import json
import re
import sys
from pathlib import Path

from godot_coverage import VERSIONS
from runtime_warning_map import MAP

ROOT = Path(__file__).resolve().parents[1]
CALL = re.compile(r"\bWARN_PRINT(?:_ONCE)?(?:_ED)?\(")
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')
DIRECTORIES = ("servers", "drivers", "scene", "modules")


def extract(root):
    found = []
    for directory in DIRECTORIES:
        for path in sorted((root / directory).rglob("*")):
            if path.suffix not in (".cpp", ".h", ".mm") or "tests" in path.parts or "thirdparty" in path.parts:
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            rel = path.relative_to(root).as_posix()
            for match in CALL.finditer(text):
                if text[max(0, match.start() - 8):match.start()].endswith("define "):
                    continue  # the macro definitions themselves
                depth, index = 1, match.end()
                while depth and index < len(text):
                    depth += {"(": 1, ")": -1}.get(text[index], 0)
                    index += 1
                argument = text[match.end():index - 1]
                literals = STRING.findall(argument)
                message = "".join(literals) if literals else "<" + " ".join(argument.split()) + ">"
                found.append((rel, message, text[:match.start()].count("\n") + 1))
    return found


SYNC_HEADERS = {
    "RENDERING": ["servers/rendering/rendering_server_default.h"],
    "PHYSICS_3D": ["servers/physics_3d/physics_server_3d_wrap_mt.h", "servers/physics_server_3d_wrap_mt.h"],
    "PHYSICS_2D": ["servers/physics_2d/physics_server_2d_wrap_mt.h", "servers/physics_server_2d_wrap_mt.h"],
}
SYNC_MACRO = re.compile(r"\bFUNC\d+RC?\(")


def sync_calls(root):
    """Method names wrapped by FUNCnR/FUNCnRC: called off the server thread they push a command and wait for the result."""
    found = {}
    for key, candidates in SYNC_HEADERS.items():
        path = next((root / rel for rel in candidates if (root / rel).is_file()), None)
        assert path is not None, f"{root}: no {key} wrapper header"
        text = path.read_text(encoding="utf-8", errors="replace")
        names = set()
        for match in SYNC_MACRO.finditer(text):
            if text[max(0, match.start() - 8):match.start()].endswith("define "):
                continue
            depth, index, args, current = 1, match.end(), [], ""
            while depth and index < len(text):
                char = text[index]
                depth += {"(": 1, "<": 1, ")": -1, ">": -1}.get(char, 0)
                if char == "," and depth == 1:
                    args.append(current.strip())
                    current = ""
                elif depth:
                    current += char
                index += 1
            args.append(current.strip())
            if len(args) >= 2 and re.fullmatch(r"\w+", args[1]):
                names.add(args[1])
        found[key] = names
    return found


def write_sync_calls(per_version):
    lines = ["## Generated by scripts/godot_runtime_warnings.py from Godot 4.4 to 4.7.2; do not edit.",
             "## Server methods that wait for the server thread when called from another thread (MAIN_THREAD_SYNC_CHECK).", ""]
    for key in SYNC_HEADERS:
        names = sorted(set().union(*(calls[key] for calls in per_version)))
        lines.append(f"const {key} := [")
        for start in range(0, len(names), 6):
            lines.append("\t" + " ".join(f'"{name}",' for name in names[start:start + 6]))
        lines.append("]")
    (ROOT / "addons/render_lens/server_sync_calls.gd").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def resolve(path, message):
    for path_pattern, message_pattern, target in MAP:
        if re.search(path_pattern, path) and re.search(message_pattern, message):
            return target
    return None


def main():
    dump = "--dump" in sys.argv
    sources = [arg for arg in sys.argv[1:] if arg != "--dump"]
    entries = {}
    if not dump:
        write_sync_calls([sync_calls(Path(source)) for source in sources])
    for version, source in zip(VERSIONS, sources):
        for rel, message, line in extract(Path(source)):
            # Keyed by file stem: renamed or moved files (servers/audio_server.cpp, Metal .mm -> .cpp) keep one entry.
            entry = entries.setdefault((Path(rel).stem, message), {"file": rel, "message": message, "source": {}})
            entry["file"] = rel
            entry["source"].setdefault(version, f"https://github.com/godotengine/godot/blob/{VERSIONS[version]}/{rel}#L{line}")
    if dump:
        for entry in sorted(entries.values(), key=lambda item: (item["file"], item["message"])):
            print(f"{entry['file']} | {','.join(entry['source'])} | {entry['message'][:220]}")
        return
    rules = {}
    for path in (ROOT / "addons/render_lens/rules").glob("*.json"):
        for rule in json.loads(path.read_text(encoding="utf-8")):
            rules[rule["id"]] = rule
    unmapped = []
    for entry in entries.values():
        rel, message = entry["file"], entry["message"]
        target = resolve(rel, message)
        if target is None:
            unmapped.append(f"{rel}: {message[:100]}")
            continue
        kind, _, detail = target.partition(":")
        if kind == "rule":
            assert detail in rules, f"{rel}: mapped rule {detail} is missing"
            verified = set(rules[detail]["applies_to"]["versions"])
            # A covering rule must be verified on every version that prints the message (4.7.2 -> 4.7).
            unverified = sorted({version.rsplit(".", 1)[0] if version.count(".") == 2 else version for version in entry["source"]} - verified)
            assert not unverified, f"{rel}: rule {detail} is not verified on {unverified} where Godot prints: {message[:80]}"
            entry["status"] = "covered"
            entry["rule"] = detail
        else:
            entry["status"] = "excluded"
            entry["category"] = kind
            entry["reason"] = detail
    assert not unmapped, "Unmapped runtime warnings:\n" + "\n".join(unmapped)
    items = sorted(entries.values(), key=lambda item: (item["file"], item["message"]))
    categories = {}
    for item in items:
        categories[item.get("category", "covered")] = categories.get(item.get("category", "covered"), 0) + 1
    document = {
        "scope": "Every WARN_PRINT, WARN_PRINT_ONCE, WARN_PRINT_ED and WARN_PRINT_ONCE_ED call in servers/, drivers/, scene/ and modules/ of Godot 4.4-stable, 4.5.2-stable, 4.6.3-stable and 4.7.2-stable, extracted from source (tests and thirdparty excluded). Messages are keyed by file name and text: a message in a moved or renamed file is listed once, and a message whose text changed between versions is listed once per text.",
        "versions": VERSIONS,
        "method": "Render Lens does not read logs. A message is covered when a rule reports, from stored scene or project state (or the per-frame script scan), the configuration that makes Godot print it. Excluded messages give the reason in one of these categories: environment (hardware, driver, operating system, display server or platform), script (a script or API call at runtime, not stored state), editor (editor, import or build tooling), internal (engine bugs, leaks or developer diagnostics), clamped (Godot corrects the value itself; the warning describes the correction) and content (malformed or unsupported asset data).",
        "summary": {"messages": len(items), **dict(sorted(categories.items()))},
        "warnings": items,
    }
    (ROOT / "docs/GODOT_RUNTIME_WARNINGS.json").write_text(json.dumps(document, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(document["summary"])


if __name__ == "__main__":
    main()
